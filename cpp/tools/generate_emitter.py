import argparse
import json
from pathlib import Path

PRIMITIVE_RENAMES = {
    "and": "bool_and",
    "or": "bool_or",
    "not": "bool_not",
    "xor": "bool_xor",
}

LITERAL_TYPES = {
    "bool-literal": "bool",
    "int": "IntLiteral",
    "range": "RangeLiteral",
    "bounded-range": "BoundedRangeLiteral",
}


def type_name(name: str) -> str:
    return "".join(part.capitalize() for part in name.replace("_", "-").split("-"))


def moved_argument(argument: dict) -> str:
    name = argument["name"]
    if argument["type"] == "bool-literal" and not argument["variadic"]:
        return name
    return f"std::move({name})"


class CodeGenerator:
    def __init__(self, schema: dict) -> None:
        self.schema = schema
        self.header = ["// Generated by generate_emitter.py. Do not edit.", ""]
        self.source = self.header.copy()
        self.cpp_types = {}
        self.expression_types = []
        self.collected_options = {}

        self.collect_types()
        self.collect_options()

        self.generate_enums()
        self.generate_expression_types()
        self.generate_option_wrappers()
        self.generate_primitives()
        self.generate_statements()

    def collect_types(self):
        for entry in self.schema["types"]:
            name = entry["name"]
            cpp_name = type_name(name)
            match entry["kind"]:
                case "expression":
                    self.expression_types.append(cpp_name)
                    self.cpp_types[name] = f"{cpp_name}Expr"
                case "literal":
                    self.cpp_types[name] = LITERAL_TYPES[name]
                case "enum":
                    self.cpp_types[name] = cpp_name
                case _:
                    raise ValueError(f"Unsupported type kind: {entry['kind']}")

    def collect_options(self):
        for statement in self.schema["statements"]:
            for option in statement["options"]:
                name = option["name"]
                if name in self.collected_options:
                    previous = self.collected_options[name]
                    if any(previous[key] != option[key] for key in ("type", "keyword")):
                        raise ValueError(f"Inconsistent definition of option: {name}")
                else:
                    self.collected_options[name] = option

    def generate_enums(self):
        for entry in self.schema["types"]:
            if entry["kind"] == "enum":
                self.generate_enum(type_name(entry["name"]), entry["values"])

    def generate_enum(self, cpp_name: str, values: list[str]) -> None:
        self.header.append(f"enum class {cpp_name} {{")
        self.header.extend(f"  {type_name(value)}," for value in values)
        self.header.append("};\n")
        signature = f"void emit(SExprPrinter &printer, {cpp_name} value)"
        self.header.append(signature + ";\n")
        self.source.extend([signature + " {", "  switch (value) {"])
        for value in values:
            self.source.extend(
                [
                    f"  case {cpp_name}::{type_name(value)}:",
                    f"    return printer.identifier({json.dumps(value)});",
                ]
            )
        self.source.extend(
            [
                "  }",
                f'  throw std::invalid_argument("invalid {cpp_name}");',
                "}\n",
            ]
        )

    def generate_expression_types(self):
        self.header.append("enum class Type {")
        self.header.extend(f"  {name}," for name in self.expression_types)
        self.header.append("};\n")
        for name in self.expression_types:
            self.header.append(f"using {name}Expr = Expr<Type::{name}>;")
            self.header.append(f"using {name}Id = Identifier<Type::{name}>;")
        self.header.append("")

    def generate_option_wrappers(self):
        self.header.append("namespace option {")
        for option in self.collected_options.values():
            cpp_type = self.cpp_types[option["type"]]
            if option["type"] != "bool-literal":
                cpp_type = f"property_ir::{cpp_type}"
            struct_name = type_name(option['name'])
            self.header.append(f"struct {struct_name} {{")
            if option["default"] == None:
                cpp_type = f"std::optional<{cpp_type}>"
                self.header.extend([
                    f"  const {cpp_type} value;",
                    f"  {struct_name}({cpp_type} value = std::nullopt) : value{{value}} {{}}",
                ])
            else:
                self.header.append(f"  const {cpp_type} value;")
            self.header.append("};")
        self.header.append("}\n")
        for option in self.collected_options.values():
            cpp_name = f"option::{type_name(option['name'])}"
            signature = f"void emit(SExprPrinter &printer, const {cpp_name} &value)"
            self.header.append(signature + ";")
            if option["default"] == None:
                self.source.extend(
                    [
                        signature + " {",
                        "  if (value.value.has_value()) {",
                        f"    printer.identifier({json.dumps(option['keyword'])});",
                        "    detail::emit_argument(printer, value.value.value());",
                        "  }",
                        "}\n",
                    ]
                )
            else:
                self.source.extend(
                    [
                        signature + " {",
                        f"  printer.identifier({json.dumps(option['keyword'])});",
                        "  detail::emit_argument(printer, value.value);",
                        "}\n",
                    ]
                )
        self.header.append("")

    def generate_primitives(self):
        for instance in self.schema["primitives"]:
            ir_name: str = instance["name"]
            name = PRIMITIVE_RENAMES.get(ir_name, ir_name.replace("-", "_"))
            result = self.cpp_types[instance["result"]]
            self.generate_primitive(ir_name, name, result, instance["arguments"])

    def generate_statements(self):
        for instance in self.schema["statements"]:
            ir_name = instance["name"]
            name = ir_name.replace("-", "_")
            self.generate_statement(
                ir_name, name, instance["arguments"], instance["options"]
            )

        for name in self.expression_types:
            self.source.append(
                f"template Statement declare({name}Id name, {name}Expr value);"
            )

    def parameters(self, arguments: list[dict], list_type: str) -> str:
        result = []
        for argument in arguments:
            cpp_type = self.cpp_types[argument["type"]]
            if argument["variadic"]:
                cpp_type = f"{list_type}<{cpp_type}>"
            result.append(f"{cpp_type} {argument['name']}")
        return ", ".join(result)

    def generate_primitive(
        self,
        ir_name: str,
        name: str,
        result: str,
        arguments: list[dict],
    ) -> None:
        signature = f"{result} {name}({self.parameters(arguments, 'std::vector')})"
        self.header.append(signature + ";")
        call_arguments = [json.dumps(ir_name)] + [
            moved_argument(arg) for arg in arguments
        ]
        self.source.extend(
            [
                signature + " {",
                f"  return detail::application<{result}>({', '.join(call_arguments)});",
                "}\n",
            ]
        )

        if any(arg["variadic"] for arg in arguments):
            signature = f"{result} {name}({self.parameters(arguments, 'std::initializer_list')})"
            self.header.append(signature + ";")
            call_arguments = [
                f"std::vector<{self.cpp_types[arg['type']]}>({arg['name']})"
                if arg["variadic"]
                else moved_argument(arg)
                for arg in arguments
            ]
            self.source.extend(
                [
                    signature + " {",
                    f"  return {name}({', '.join(call_arguments)});",
                    "}\n",
                ]
            )
            if len(arguments) == 1:
                element_type = self.cpp_types[arguments[0]["type"]]
                self.header.extend(
                    [
                        "template <typename... Args,",
                        "          std::enable_if_t<",
                        f"              (std::is_convertible_v<Args&&, {element_type}> && ...), int> = 0>",
                        f"{result} {name}(Args&&... args) {{",
                        f"  return {name}(std::vector<{element_type}>{{std::forward<Args>(args)...}});",
                        "}\n",
                    ]
                )

    def generate_statement(
        self,
        ir_name: str,
        name: str,
        arguments: list[dict],
        options: list[dict],
    ) -> None:
        option_type = f"{type_name(ir_name)}Option"
        if options:
            alternatives = ",\n    ".join(
                f"option::{type_name(option['name'])}" for option in options
            )
            self.header.append(
                f"using {option_type} = std::variant<\n    {alternatives}>;\n"
            )

        positional_params = [
            f"{self.cpp_types[arg['type']]} {arg['name']}" for arg in arguments
        ]

        def signature(default: bool = False) -> str:
            params = positional_params.copy()
            if options:
                suffix = " = {}" if default else ""
                params.append(f"std::initializer_list<{option_type}> options{suffix}")
            return f"Statement {name}({', '.join(params)})"

        self.header.append(signature(default=True) + ";")
        call_arguments = [json.dumps(ir_name)] + [
            moved_argument(arg) for arg in arguments
        ]
        self.source.append(signature() + " {")
        if options:
            self.source.extend(
                [
                    f"  bool seen[{len(options)}] = {{}};",
                    "  for (const auto &option : options) {",
                    "    if (seen[option.index()])",
                    f'      throw std::invalid_argument("duplicate option for {ir_name}");',
                    "    seen[option.index()] = true;",
                    "  }",
                ]
            )
            call_arguments.append(f"std::vector<{option_type}>(options)")
        self.source.extend(
            [
                f"  return detail::application<Statement>({', '.join(call_arguments)});",
                "}\n",
            ]
        )
        if options:
            params = positional_params.copy()
            params.append("Options&&... options")
            call_arguments = [moved_argument(arg) for arg in arguments]
            call_arguments.append(
                f"std::initializer_list<{option_type}>{{std::forward<Options>(options)...}}"
            )
            self.header.extend(
                [
                    "template <typename... Options,",
                    "          std::enable_if_t<",
                    f"              (std::is_convertible_v<Options&&, {option_type}> && ...), int> = 0>",
                    f"Statement {name}({', '.join(params)}) {{",
                    f"  return {name}({', '.join(call_arguments)});",
                    "}\n",
                ]
            )

    @property
    def header_contents(self) -> str:
        return "\n".join(self.header) + "\n"

    @property
    def source_contents(self) -> str:
        return "\n".join(self.source) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("schema", type=Path)
    parser.add_argument("header", type=Path)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    generator = CodeGenerator(json.loads(args.schema.read_text()))
    args.header.write_text(generator.header_contents)
    args.source.write_text(generator.source_contents)
