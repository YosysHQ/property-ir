import argparse
import json
from pathlib import Path

PRIMITIVE_RENAMES = {
    "and": "bool_and",
    "or": "bool_or",
    "not": "bool_not",
    "xor": "bool_xor",
}

LITERAL_TYPES = {
    "bool-literal": "bool",
    "int": "IntLiteral",
    "range": "RangeLiteral",
    "bounded-range": "BoundedRangeLiteral",
}


def type_name(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("-"))


def parameters(arguments: list[dict], cpp_types: dict[str, str], list_type: str) -> str:
    result = []
    for argument in arguments:
        cpp_type = cpp_types[argument["type"]]
        if argument["variadic"]:
            cpp_type = f"{list_type}<{cpp_type}>"
        result.append(f"{cpp_type} {argument['name']}")
    return ", ".join(result)


def moved_argument(argument: dict) -> str:
    name = argument["name"]
    if argument["type"] == "bool-literal" and not argument["variadic"]:
        return name
    return f"std::move({name})"


def generate(schema: dict) -> tuple[str, str]:
    header = ["// Generated by generate_emitter.py. Do not edit.", ""]
    source = header.copy()
    cpp_types = {}
    expression_types = []

    for entry in schema["types"]:
        name = entry["name"]
        cpp_name = type_name(name)
        match entry["kind"]:
            case "expression":
                expression_types.append(cpp_name)
                cpp_types[name] = f"{cpp_name}Expr"
            case "literal":
                cpp_types[name] = LITERAL_TYPES[name]
            case "enum":
                cpp_types[name] = cpp_name
                header.append(f"enum class {cpp_name} {{")
                header.extend(f"  {type_name(value)}," for value in entry["values"])
                header.append("};\n")
            case _:
                raise ValueError(f"Unsupported type kind: {entry['kind']}")

    header.append("enum class Type {")
    header.extend(f"  {name}," for name in expression_types)
    header.append("};\n")
    for name in expression_types:
        header.append(f"using {name}Expr = Expr<Type::{name}>;")
        header.append(f"using {name}Id = Identifier<Type::{name}>;")
    header.append("")

    for primitive in schema["primitives"]:
        ir_name = primitive["name"]
        name = PRIMITIVE_RENAMES.get(ir_name, ir_name.replace("-", "_"))
        result = cpp_types[primitive["result"]]
        arguments = primitive["arguments"]
        signature = (
            f"{result} {name}({parameters(arguments, cpp_types, 'std::vector')})"
        )
        header.append(signature + ";")
        call_arguments = [json.dumps(ir_name)] + [
            moved_argument(arg) for arg in arguments
        ]
        source.extend(
            [
                signature + " {",
                f"  return detail::application<{result}>({', '.join(call_arguments)});",
                "}\n",
            ]
        )

        if any(arg["variadic"] for arg in arguments):
            signature = f"{result} {name}({parameters(arguments, cpp_types, 'std::initializer_list')})"
            header.append(signature + ";")
            call_arguments = [
                f"std::vector<{cpp_types[arg['type']]}>({arg['name']})"
                if arg["variadic"]
                else moved_argument(arg)
                for arg in arguments
            ]
            source.extend(
                [
                    signature + " {",
                    f"  return {name}({', '.join(call_arguments)});",
                    "}\n",
                ]
            )

            if len(arguments) == 1:
                element_type = cpp_types[arguments[0]["type"]]
                header.extend(
                    [
                        "template <typename... Args,",
                        "          std::enable_if_t<",
                        f"              (std::is_convertible_v<Args&&, {element_type}> && ...), int> = 0>",
                        f"{result} {name}(Args&&... args) {{",
                        f"  return {name}(std::vector<{element_type}>{{std::forward<Args>(args)...}});",
                        "}\n",
                    ]
                )

    for name in expression_types:
        source.append(f"template Statement declare({name}Id name, {name}Expr value);")

    return "\n".join(header) + "\n", "\n".join(source) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("schema", type=Path)
    parser.add_argument("header", type=Path)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    header, source = generate(json.loads(args.schema.read_text()))
    args.header.write_text(header)
    args.source.write_text(source)
